export function isoWeek(date = new Date()) {
  const utcDate = new Date(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()));
  const day = utcDate.getUTCDay() || 7;
  utcDate.setUTCDate(utcDate.getUTCDate() + 4 - day);
  const weekYear = utcDate.getUTCFullYear();
  const yearStart = new Date(Date.UTC(weekYear, 0, 1));
  const week = Math.ceil((((utcDate - yearStart) / 86400000) + 1) / 7);
  return { year: weekYear, week };
}

export function currentComeFollowMeLesson(date = new Date()) {
  const current = isoWeek(date);
  if (current.year !== scheduleYear) return null;
  return lessons.find((lesson) => lesson.week === current.week) ?? null;
}

export function splitLessonTitle(title) {
  const separator = title.lastIndexOf(": ");
  const heading = separator === -1 ? title : title.slice(0, separator);
  const reading = separator === -1 ? "" : title.slice(separator + 2);
  return {
    heading: heading.replace(/^(.+?)\. /, "$1: "),
    reading,
  };
}
